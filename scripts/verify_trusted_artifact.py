#!/usr/bin/env python3
"""Re-verify the trusted preflight artifact immediately before publish.

Independent of job dependency truth: checks required gate/workflow records,
generation run identity, candidate commit/provenance and bytes, and recomputes
the Docker image ID from image.tar config blob.
"""
import argparse, hashlib, json, pathlib, sys, tarfile

REQUIRED_GATES = ["go_unit_race","provider_contract","sandbox_infra","application_e2e",
 "browser_admin_core","backup_restore","supply_chain","same_artifact","arm64_service","staging_acceptance"]
REQUIRED_RUNS = ["ci","r12-integration","r16-sandbox-e2e","r17-browser-e2e","supply-chain","staging-acceptance","same-artifact"]

def sha(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for b in iter(lambda: f.read(1 << 20), b""):
            h.update(b)
    return h.hexdigest()

def fail(msg):
    print("PUBLISH_REVALIDATION_FAIL: " + msg, file=sys.stderr); return 1

def actual_image_id(tar_path):
    with tarfile.open(tar_path, "r") as tf:
        manifest = json.loads(tf.extractfile("manifest.json").read())
        config = tf.extractfile(manifest[0]["Config"]).read()
    return "sha256:" + hashlib.sha256(config).hexdigest()

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--preflight", required=True)
    ap.add_argument("--candidate", required=True)
    ap.add_argument("--commit", required=True)
    ap.add_argument("--run-id", required=True, type=int)
    ap.add_argument("--run-attempt", required=True, type=int)
    a = ap.parse_args()
    try:
        pf = json.load(open(a.preflight))
    except Exception as ex:
        return fail(f"preflight unreadable: {ex}")
    if pf.get("status") != "PASS" or pf.get("release_authorized") is not False:
        return fail("preflight not PASS or authorization field changed")
    if pf.get("commit") != a.commit:
        return fail("preflight commit mismatch")
    if pf.get("gate_source") != "github-actions-api":
        return fail("preflight not from trusted GitHub API source")
    if pf.get("generation_run_id") != a.run_id or pf.get("generation_run_attempt") != a.run_attempt:
        return fail("preflight was generated by a different workflow run/attempt")
    runs = pf.get("ci_runs") or {}
    for name in REQUIRED_RUNS:
        rec = runs.get(name)
        if not rec:
            return fail(f"missing required workflow record {name}")
        if not rec.get("verified"):
            return fail(f"{name} gate record not verified")
        if name != "same-artifact" and rec.get("event") != "push":
            return fail(f"{name} gate record event is not push")
        if name != "same-artifact" and rec.get("commit") != a.commit:
            return fail(f"{name} gate record commit mismatch")
    gates = pf.get("gates") or {}
    for gate in REQUIRED_GATES:
        if gates.get(gate) != "PASS":
            return fail(f"required gate {gate} not PASS")
    c = pathlib.Path(a.candidate)
    if (c / "commit.txt").read_text().strip() != a.commit:
        return fail("candidate commit.txt mismatch")
    prov = json.loads((c / "candidate-provenance.json").read_text())
    if prov.get("commit") != a.commit:
        return fail("candidate provenance commit mismatch")
    computed = actual_image_id(c / "image.tar")
    if (c / "image-id.txt").read_text().strip() != computed:
        return fail("candidate image-id.txt does not match image.tar config")
    if pf.get("candidate_image_id") != computed:
        return fail("preflight image ID does not match image.tar config")
    if prov.get("image_id") != computed:
        return fail("candidate provenance image ID mismatch")
    if sha(c / "image.tar") != pf.get("candidate_image_tar_sha256") or prov.get("image_tar_sha256") != pf.get("candidate_image_tar_sha256"):
        return fail("candidate image.tar does not match trusted preflight")
    if sha(c / "supply" / "sbom.cdx.json") != pf.get("sbom_sha256") or prov.get("sbom_sha256") != pf.get("sbom_sha256"):
        return fail("candidate SBOM does not match trusted preflight")
    print("PUBLISH_REVALIDATION_PASS")
    print("commit=" + a.commit)
    print("run_id=" + str(a.run_id) + " run_attempt=" + str(a.run_attempt))
    print("candidate_image_id=" + computed)
    print("candidate_image_tar_sha256=" + pf["candidate_image_tar_sha256"])
    return 0

if __name__ == "__main__":
    sys.exit(main())
